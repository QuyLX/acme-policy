import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { policyPath, POLICY_ROOT } from '../lib/io.mjs';
import { planPackage, planDsComponent, verifyCheckpoint, render } from '../lib/generate.mjs';

const cli = (args) => spawnSync(process.execPath, [join(POLICY_ROOT, 'bin/acme-policy.mjs'), ...args], { encoding: 'utf8' });
const fixtureRepo = () => {
  const dir = mkdtempSync(join(tmpdir(), 'acme-gen-'));
  cpSync(policyPath('showcase/fixtures/ts-repo'), dir, { recursive: true });
  return dir;
};

test('templates fail loudly on an unknown variable', () => assert.throws(() => render('{{nope}}', {}), /no value/));
test('generation is byte-identical for the same inputs (trusted-mechanism eligibility, AC-4)', () => {
  const a = planPackage({ repo: '/nonexistent', name: 'audit-log', kind: 'node-lib', description: 'x' });
  const b = planPackage({ repo: '/nonexistent', name: 'audit-log', kind: 'node-lib', description: 'x' });
  assert.deepEqual(a.files, b.files);
  assert.match(a.files['packages/audit-log/package.json'], /"generatedFrom": "package@1\.0\.0"/);
});
test('design-review checkpoint: required, must be passed, never approved by an agent', () => {
  assert.match(verifyCheckpoint(undefined, 'design-review'), /required/);
  assert.equal(verifyCheckpoint(policyPath('checks/generate/fixtures/design-review-passed.json'), 'design-review'), null);
  assert.match(verifyCheckpoint(policyPath('checks/generate/fixtures/design-review-agent.json'), 'design-review'), /agent cannot approve/);
});
test('SC-21: `generate package` without design-review refuses and writes nothing (AC-1)', () => {
  const repo = fixtureRepo();
  try {
    const r = cli(['generate', 'package', 'audit-log', '--repo', repo]);
    assert.equal(r.status, 1);
    assert.match(r.stderr, /design-review checkpoint is required/);
    assert.doesNotMatch(readFileSync(join(repo, 'factory.config.yaml'), 'utf8'), /audit-log/);
  } finally { rmSync(repo, { recursive: true, force: true }); }
});
test('`generate package` with a passed design-review writes the package, config entry and generated configs', () => {
  const repo = fixtureRepo();
  try {
    const r = cli(['generate', 'package', 'audit-log', '--repo', repo, '--checkpoint', policyPath('checks/generate/fixtures/design-review-passed.json')]);
    assert.equal(r.status, 0, r.stderr);
    assert.match(readFileSync(join(repo, 'factory.config.yaml'), 'utf8'), /"@platform\/audit-log":\n {4}kind: node-lib/);
    assert.match(readFileSync(join(repo, 'packages/audit-log/eslint.config.mjs'), 'utf8'), /GENERATED by `factory sync`/);
    assert.equal(cli(['sync', '--repo', repo, '--check']).status, 0, 'generated output must already be in sync');
  } finally { rmSync(repo, { recursive: true, force: true }); }
});
test('ds-component plan: contract clause, test and doc agree (docs-sync shape)', () => {
  const p = planDsComponent({ repo: '/nonexistent', name: 'StatusDot', summary: 'Small status indicator.' });
  const test_ = p.files['packages/ds-react/src/status-dot/StatusDot.test.tsx'];
  const contract = p.files['packages/ds-react/docs/components/StatusDot.contract.md'];
  assert.match(contract, /^id: DS-STATUSDOT$/m);
  assert.match(contract, /^\| STA-1 \|/m);
  assert.match(test_, /STA-1:/);
  assert.match(p.files['packages/ds-react/src/status-dot/StatusDot.doc.ts'], /contract: 'DS-STATUSDOT'/);
});
