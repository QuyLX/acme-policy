// Config generation from presets + factory.config.yaml (FE §8.7 item 3, FE-CFG-001; tech-design 03-presets).
// target "repo":   thin files committed in the product repo for editors and local runs; checked by meta.config-parity.
// target "verify": self-contained files the verifier writes for one run; they import the pinned kit by absolute path,
//                  so nothing in the product repo (its configs, its @acme/presets version, its scripts) changes the result.
import { readdirSync, readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { join, relative } from 'node:path';

// Next.js (Turbopack) refuses to resolve a tsconfig `extends` through a symlink that leaves the repo's filesystem
// root (verified 2026-11-24, Next.js 16.4.6), and the kit is linked from the policy repo. The kit's tsconfig files are
// therefore copied into the product repo as generated files; lint and test presets are still imported from the kit.
export const KIT_TSCONFIG_DIR = '.factory/kit/tsconfig';

export const VERIFY_FILES = { tsconfig: 'tsconfig.factory-verify.json', vitest: 'vitest.factory-verify.config.mjs', browser: 'vitest.browser.factory-verify.config.mjs' };

const TS_PRESET = { 'next-app': 'nextjs.json', 'react-lib': 'react-lib.json', 'node-lib': 'node-lib.json' };
const DEFAULT_INCLUDE = {
  'next-app': ['next-env.d.ts', 'src/**/*.ts', 'src/**/*.tsx', '.next/types/**/*.ts', '.next/dev/types/**/*.ts'],
  'react-lib': ['src/**/*.ts', 'src/**/*.tsx', 'test/**/*.ts', 'test/**/*.tsx'],
  'node-lib': ['src/**/*.ts', 'test/**/*.ts'],
};
const USES_REACT_PLUGIN = new Set(['next-app', 'react-lib']);

const header = (kitVersion, comment) => `${comment} GENERATED by \`factory sync\` from @acme/presets@${kitVersion} + factory.config.yaml. Do not edit (FE-CFG-001).`;

function eslintInput(entry, boundaries) {
  const input = { kind: entry.kind, boundaries };
  if (entry.lint && (entry.lint.rules || entry.lint.ignores)) input.lint = entry.lint;
  return input;
}

function tsconfigObject(entry, extendsPath, verify) {
  const compilerOptions = {};
  if (verify) compilerOptions.incremental = false;
  if (entry.typescript?.types) compilerOptions.types = entry.typescript.types;
  if (entry.typescript?.paths) compilerOptions.paths = entry.typescript.paths;
  const ts = { extends: extendsPath };
  if (Object.keys(compilerOptions).length) ts.compilerOptions = compilerOptions;
  ts.include = [...DEFAULT_INCLUDE[entry.kind], ...(entry.typescript?.extraInclude ?? [])];
  ts.exclude = ['node_modules'];
  return ts;
}

function vitestSource(entry, presetImport, kitVersion) {
  const input = { kind: entry.kind, test: entry.test };
  const react = USES_REACT_PLUGIN.has(entry.kind);
  return [
    header(kitVersion, '//'),
    ...(react ? ["import react from '@vitejs/plugin-react';"] : []),
    `import { createVitestConfig } from '${presetImport}';`,
    '',
    `export default createVitestConfig({ ${react ? 'plugins: [react()], ' : ''}...${JSON.stringify(input)} });`,
    '',
  ].join('\n');
}

export const TYPECHECKED = (kind) => kind !== 'node-tool';

/** Repo-level generated files: the kit's tsconfig presets. Keys are paths relative to the repo root. */
export function kitRepoFiles(kitDir, kitVersion) {
  const dir = join(kitDir, 'tsconfig');
  return Object.fromEntries(
    readdirSync(dir)
      .filter((f) => f.endsWith('.json'))
      .sort()
      .map((f) => [`${KIT_TSCONFIG_DIR}/${f}`, `${header(kitVersion, '//')}\n${readFileSync(join(dir, f), 'utf8')}`]),
  );
}

function browserSource(entry, presetImport, kitVersion) {
  const tw = entry.test.browser.tailwind;
  return [
    header(kitVersion, '//'),
    "import react from '@vitejs/plugin-react';",
    ...(tw ? ["import tailwindcss from '@tailwindcss/vite';"] : []),
    "import { playwright } from '@vitest/browser-playwright';",
    `import { createVitestBrowserConfig } from '${presetImport}';`,
    '',
    `export default createVitestBrowserConfig({ kind: ${JSON.stringify(entry.kind)}, plugins: [react()${tw ? ', tailwindcss()' : ''}], provider: playwright() });`,
    '',
  ].join('\n');
}

/** Files committed in a product project directory. Keys are paths relative to the project directory. */
export function repoFiles(entry, { kitVersion, boundaries, projectDir = '.' }) {
  const files = {
    'eslint.config.mjs': [
      header(kitVersion, '//'),
      "import { createEslintConfig } from '@acme/presets/eslint';",
      '',
      `export default createEslintConfig(${JSON.stringify(eslintInput(entry, boundaries))});`,
      '',
    ].join('\n'),
  };
  if (TYPECHECKED(entry.kind)) files['tsconfig.json'] = `${header(kitVersion, '//')}\n${JSON.stringify(tsconfigObject(entry, `${relative(projectDir, KIT_TSCONFIG_DIR)}/${TS_PRESET[entry.kind]}`, false), null, 2)}\n`;
  if (entry.test) files['vitest.config.ts'] = vitestSource(entry, '@acme/presets/vitest', kitVersion);
  if (entry.test?.browser) files['vitest.browser.config.ts'] = browserSource(entry, '@acme/presets/vitest', kitVersion);
  return files;
}

/** Files the verifier writes for one run. `eslint` goes to a temp work dir; tsconfig and vitest go into the project
 *  directory (their relative paths and plugin imports must resolve from there) and are deleted after the run. */
export function verifyFiles(entry, { kitDir, kitVersion, boundaries }) {
  const url = (p) => pathToFileURL(join(kitDir, p)).href;
  const files = {
    eslint: [
      `import { createEslintConfig } from '${url('eslint/index.mjs')}';`,
      `export default createEslintConfig(${JSON.stringify(eslintInput(entry, boundaries))});`,
      '',
    ].join('\n'),
  };
  if (TYPECHECKED(entry.kind)) files.tsconfig = `${JSON.stringify(tsconfigObject(entry, join(kitDir, 'tsconfig', TS_PRESET[entry.kind]), true), null, 2)}\n`;
  if (entry.test) files.vitest = vitestSource(entry, url('vitest/index.mjs'), kitVersion);
  if (entry.test?.browser) files.browser = browserSource(entry, url('vitest/index.mjs'), kitVersion);
  return files;
}
